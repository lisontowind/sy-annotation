import { selectStyle } from "./style-picker-test-helpers.mjs";
import { chromium } from "playwright";
import assert from "node:assert/strict";
import { startPreview } from "./preview.mjs";

const { server, url } = await startPreview(0);
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || "msedge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(20000);
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(url);
  await page.waitForSelector(".sya-card");
  await page.evaluate(async () => {
    const p = window.annotationPreview;
    await p.plugin.commitTools([...p.plugin.config.tools, { id: "old", label: "旧固定色工具", color: "#fff1b3", marks: [], styles: { "background-color": "#fff1b3", "font-weight": "bold" } }]);
    p.protyle.block.rootID = "theme-test";
    p.protyle.wysiwyg.element.innerHTML = '<div data-node-id="pair" data-type="NodeParagraph"><div contenteditable="true"><span data-type="text" style="color:light-dark(#112233,#ddeeff);background-color:var(--b3-font-background12)">双主题标注</span></div></div><div data-node-id="old" data-type="NodeParagraph"><div contenteditable="true"><span data-type="a strong text" data-href="https://example.test" style="background-color:#fff1b3;font-weight:bold">旧标注链接</span></div></div>';
    p.bus.emit("switch-protyle", { protyle: p.protyle });
  });
  const card = text => page.locator(".sya-card").filter({ hasText: text });
  await card("双主题标注").waitFor();
  const sampleColor = () => card("双主题标注").locator(".sya-card__sample").evaluate(node => getComputedStyle(node).color);
  assert.equal(await sampleColor(), "rgb(17, 34, 51)");
  const transactions = await page.evaluate(() => window.annotationPreview.transactions);
  await page.locator("#theme-toggle").click();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('[data-node-id="pair"] span')).color === "rgb(221, 238, 255)");
  assert.equal(await sampleColor(), "rgb(221, 238, 255)");
  assert.equal(await page.evaluate(() => window.annotationPreview.transactions), transactions, "theme switches never write annotations");
  await page.locator(".sya-more-filters").click();
  await page.locator(".sya-add-condition").click();
  await page.locator(".sya-rule-field").selectOption("signature");
  const signature = await page.locator(".sya-rule-value option").evaluateAll(options => options.find(option => option.textContent.includes("双主题标注"))?.value);
  assert.match(signature, /light-dark/);
  await page.locator(".sya-rule-value").selectOption(signature);
  await page.locator(".sya-filter-apply").click();
  await page.waitForFunction(() => document.querySelectorAll(".sya-card").length === 1);
  await page.locator("#theme-toggle").click();
  await page.waitForFunction(() => !document.querySelector('.sya-tree[aria-busy="true"]'));
  assert.equal(await sampleColor(), "rgb(17, 34, 51)");
  assert.equal(await page.locator(".sya-card").count(), 1);
  await page.locator(".sya-more-filters").click();
  await page.getByRole("button", { name: "清空筛选规则", exact: true }).click();
  await page.locator(".sya-filter-apply").click();

  await page.evaluate(() => {
    const data = { version: 2, styles: [{ id: "20261115090002-themebg", name: "原生浅深背景", light: { backgroundColor: "#ffeedd" }, dark: { backgroundColor: "#443322" } }], builtin: { colors: [], styles: [], hidden: { color: [], backgroundColor: [], style1: [] } }, order: { color: [], backgroundColor: [], style1: [] } };
    window.annotationPreview.setNativeStyles(data);
  });
  await page.waitForFunction(() => window.annotationPreview.plugin.availableTools.some(tool => tool.id === "native:custom:20261115090002-themebg"));
  await page.locator(".sya-panel .sya-palette summary").click();
  await page.locator(".sya-panel .sya-manage-tools").click();
  await page.getByRole("button", { name: "新建工具", exact: true }).click();
  await page.locator('[data-field="label"]').fill("原生配色组合");
  await selectStyle(page, '.sya-manager [data-color-property="color"]', "native:color:3");
  await selectStyle(page, '.sya-manager [data-color-property="background-color"]', "native:custom:20261115090002-themebg");
  assert.equal(await page.locator('.sya-manager input[type="color"]').count(), 0, "global colors are managed by SiYuan");
  await page.locator(".sya-save-tool").click();
  await page.waitForFunction(() => document.querySelector(".sya-manager__error")?.textContent.includes("已保存"));
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("tools.json")).tools.find(tool => tool.label === "原生配色组合"));
  assert.equal(saved.styles.color, "var(--b3-font-color3)"); assert.match(saved.styles["background-color"], /--b3-inline-style-20261115090002-themebg-background-color/);
  await page.locator(".sya-manager__advanced summary").click();
  await page.locator(".sya-repair-colors").click();
  await page.locator(".sya-color-repair-dialog").waitFor();
  assert.equal(await page.locator(".sya-repair-execute").isDisabled(), true);
  const oldRow = page.locator(".sya-repair-row").filter({ hasText: "rgb(255,241,179)" });
  assert.equal(await oldRow.count(), 1, "native default entries do not interrupt legacy color suggestions");
  await oldRow.locator(".sya-repair-enabled").check();
  await page.locator(".sya-repair-preview").click();
  await page.waitForFunction(() => !document.querySelector(".sya-repair-execute").disabled);
  await page.locator("#theme-toggle").evaluate(node => node.click());
  await page.waitForFunction(() => document.querySelector(".sya-repair-execute").disabled);
  await page.locator(".sya-repair-preview").click();
  await page.waitForFunction(() => !document.querySelector(".sya-repair-execute").disabled);
  await page.locator(".sya-repair-execute").click();
  await page.waitForFunction(() => document.querySelector(".sya-color-repair-dialog .sya-dialog-status")?.textContent === "颜色修复已完成");
  assert.equal(await page.evaluate(() => window.annotationPreview.plugin.config.tools.find(tool => tool.id === "old").styles["background-color"]), "var(--b3-font-background12)");
  assert.ok(await page.evaluate(() => localStorage.getItem("tools-theme-backup.json")));
  await page.locator(".sya-repair-restore").click();
  await page.waitForFunction(() => window.annotationPreview.plugin.config.tools.find(tool => tool.id === "old").styles["background-color"] === "#fff1b3");
  await page.locator(".sya-repair-scope").selectOption("document");
  const docRow = page.locator(".sya-repair-row").filter({ hasText: "rgb(255,241,179)" });
  await docRow.locator(".sya-repair-enabled").check();
  await selectStyle(page, '.sya-repair-row:has-text("rgb(255,241,179)")', "native:backgroundColor:12");
  await page.locator(".sya-repair-preview").click();
  await page.waitForFunction(() => !document.querySelector(".sya-repair-execute").disabled);
  const beforeRepair = await page.evaluate(() => window.annotationPreview.transactions);
  await page.locator(".sya-repair-execute").click();
  await page.waitForFunction(() => document.querySelector(".sya-color-repair-dialog .sya-dialog-status")?.textContent === "颜色修复已完成");
  assert.equal(await page.evaluate(() => window.annotationPreview.transactions), beforeRepair + 1);
  assert.match(await page.locator('[data-node-id="old"]').innerHTML(), /var\(--b3-font-background12\)/);
  assert.equal(await page.locator('[data-node-id="old"] [data-href]').getAttribute("data-href"), "https://example.test");
  await page.evaluate(() => window.annotationPreview.undo());
  await page.waitForFunction(() => !document.querySelector('[data-node-id="old"] span').style.backgroundColor.includes("var("));
  await page.screenshot({ path: "test-results/theme-colors.png" });
  const legacy = await browser.newPage();
  await legacy.addInitScript(() => {
    const supports = CSS.supports.bind(CSS);
    CSS.supports = (property, value) => value?.includes("light-dark(") ? false : supports(property, value);
  });
  await legacy.goto(url); await legacy.waitForSelector(".sya-card");
  await legacy.evaluate(async () => {
    const p = window.annotationPreview;
    await p.plugin.commitTools([{ id: "legacy-pair", label: "旧浏览器双配色", color: "#112233", marks: [], styles: { color: "light-dark(#112233, #ddeeff)" } }]);
    p.plugin.chooseTool("legacy-pair");
    p.protyle.block.rootID = "legacy-pair";
    p.protyle.wysiwyg.element.innerHTML = '<div data-node-id="legacy" data-type="NodeParagraph"><div contenteditable="true">兼容颜色</div></div>';
    p.bus.emit("switch-protyle", { protyle: p.protyle });
  });
  await legacy.waitForFunction(() => window.annotationPreview.plugin.rootId === "legacy-pair" && !window.annotationPreview.plugin.loading);
  await legacy.evaluate(() => {
    const p = window.annotationPreview, editable = p.protyle.wysiwyg.element.querySelector('[contenteditable="true"]');
    editable.focus(); const range = document.createRange(); range.selectNodeContents(editable);
    getSelection().removeAllRanges(); getSelection().addRange(range); p.plugin.paint(false);
  });
  await legacy.waitForSelector(".sya-card__sample");
  assert.match(await legacy.locator('[data-node-id="legacy"]').innerHTML(), /--b3-legacy-light-color/);
  assert.equal(await legacy.locator('.sya-card__sample').evaluate(node => getComputedStyle(node).color), "rgb(17, 34, 51)");
  await legacy.locator('#theme-toggle').click();
  assert.equal(await legacy.locator('.sya-card__sample').evaluate(node => getComputedStyle(node).color), "rgb(221, 238, 255)");
  await legacy.close();
  assert.deepEqual(errors, []);
  console.log("Theme browser passed: native references, preserved legacy pairs, theme-aware Worker filters, preview invalidation, tool backup/restore and one-transaction document repair.");
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
